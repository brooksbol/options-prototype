#!/usr/bin/env python3
"""Promote actual synthetic source->HTTP captures; financial assertions live in Java, not an expected-file oracle.
Run PortfolioDocumentationExamplesTest first. --check checks committed provenance/semantics; promotion is explicit.
"""
import argparse,json,copy
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[3]
p=argparse.ArgumentParser();p.add_argument('--promote',action='store_true');args=p.parse_args()
source=ROOT/'evidence-service-java/build/product-conformance/examples'
if args.promote:
 (HERE/'examples').mkdir(exist_ok=True)
 for path in source.glob('*.json'):(HERE/'examples'/path.name).write_bytes(path.read_bytes())
records={path.stem:json.loads(path.read_text()) for path in (HERE/'examples').glob('*.json')}
assert len(records)>=12
for r in records.values():assert r['standing']=='SYNTHETIC_SOURCE_DERIVED_HTTP_NOT_LIVE_BROKERAGE_EVIDENCE' and r['status']==200
b=lambda k:records[k]['body']
assert b('simple-position')['state']=='UNRESOLVED'
assert b('simple-position')['evaluation']['brokerReportedOpenPl']['value']=='250'
assert b('simple-position')['evaluation']['grossUnrealizedPl']['value'] is None
assert b('iron-condor-position')['state']=='UNRESOLVED'
assert b('iron-condor-position')['evaluation']['openingCashFlow']['value'] is None
assert b('iron-condor-position')['evaluation']['payoff']['geometry']['valueKind']=='TERMINAL_VALUE'
assert b('iron-condor-construction')['recognition']['modelVersion']['href'].endswith('/IRON_CONDOR/versions/1')
assert b('account-coverage-conflict')['coverageAssessments'][0]['eligibleQuantity']=='100'
assert b('account-coverage-conflict')['coverageAssessments'][0]['requiredQuantity']=='200'
assert 'COVERAGE_INSUFFICIENT' in json.dumps(b('position-coverage-conflict')['warnings'])
assert b('current-holdings')['items'][0]['quantity']=='75'
assert b('historical-holdings')['items'][0]['quantity']=='100'
assert b('current-holdings')['items'][0]['snapshotId']!=b('historical-holdings')['items'][0]['snapshotId']
if args.promote:
 path=HERE.parent/'documentation-annotations.json';a=json.loads(path.read_text())
 mapping={'/v2/positions':['simple-position-collection','iron-condor-collection'],
 '/v2/positions/{positionId}':['simple-position','iron-condor-position','position-coverage-conflict'],
 '/v2/constructions/{constructionId}':['iron-condor-construction','construction-coverage-conflict'],
 '/v2/orders':['working-closing-orders'],'/v2/orders/{orderId}':['working-closing-order'],
 '/v2/accounts/{accountId}/inventory-reconciliation':['account-coverage-conflict'],
 '/v2/holdings':['current-holdings','historical-holdings','holdings-snapshot-discovery']}
 for route,names in mapping.items():
  a['operations'][route]['examples']['200']={n:{'summary':'Synthetic source-derived: '+n.replace('-',' '),'description':records[n]['source']+'; generated by actual decoder/admission/HTTP, not live brokerage verification. Account-source references are redacted in the public projection.','value':copy.deepcopy(b(n))} for n in names}
 path.write_text(json.dumps(a,indent=2)+'\n')
print('PASS: source-derived example qualifications, history separation, aggregate coverage; no invented opening occurrence')
